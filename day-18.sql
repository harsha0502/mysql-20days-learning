-- BEFORE DELETE
DELIMITER //
CREATE TRIGGER TRG_BEFORE_DELETE
BEFORE DELETE
ON EMPLOYEES
FOR EACH ROW
BEGIN
	IF OLD.DEPARTMENT = 'IT' THEN
    SIGNAL SQLSTATE '45000'
    SET MESSAGE_TEXT = 'CANNOT DELETE "IT" EMPLOYEES';
    END IF;
    END //
DELIMITER ;

