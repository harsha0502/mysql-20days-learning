-- BEFORE UPDATE
DELIMITER //
CREATE TRIGGER TRG_BEFORE_UPDATE_SALARY
BEFORE UPDATE
ON EMPLOYEES
FOR EACH ROW
BEGIN
	IF NEW.SALARY <OLD.SALARY THEN
    SIGNAL SQLSTATE '45000'
    SET MESSAGE_TEXT = 'SALARY CANNOT BE REDUCED';
    END IF;
    END //
DELIMITER ;

DROP TRIGGER TRG_BEFORE_UPDATE_SALARY;

UPDATE EMPLOYEES SET SALARY = 30000 WHERE EMP_ID = 102;

-- AFTER UPDATE
DELIMITER //
CREATE TRIGGER TRG_AFTER_UPDATE_SALARY
AFTER UPDATE
ON EMPLOYEES
FOR EACH ROW
BEGIN
	INSERT INTO EMPLOYEE_AUDIT (EMP_ID, ACTION_TYPE, OLD_SALARY, NEW_SALARY, ACTION_TIME)
    VALUES(OLD.EMP_ID, 'UPDATE', OLD.SALARY, NEW.SALARY, NOW());
    END //
DELIMITER ;

